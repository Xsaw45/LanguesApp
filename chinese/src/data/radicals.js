/** Map numéro → { n, forms: ['水', '氵'], simplified: '讠' | null, meaning: { fr, en } } */
export const RADICALS = new Map(TABLE.map(([n, forms, simplified, fr, en]) => [n, {
  n,
  forms: [...forms],
  simplified: simplified || null,
  meaning: { fr, en },
}]))

/**
 * Formes à afficher pour la clé d'un caractère : la forme simplifiée d'abord quand le caractère l'utilise (红 → 纟),
 * sinon la forme principale et ses variantes (河 → 水 氵).
 */
export function radicalForms(n, simplified) {
  const r = RADICALS.get(n)
  if (!r) return []
  return simplified && r.simplified ? [r.simplified, ...r.forms.filter(f => f !== r.simplified)] : r.forms
}
